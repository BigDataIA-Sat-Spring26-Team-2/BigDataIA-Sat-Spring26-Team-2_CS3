class DocumentFormat(str, Enum):
    PDF = "pdf"
    HTML = "html"


@dataclass
class ParsedDocument:
    company_ticker: str
    filing_type: str
    filing_date: datetime
    content: str
    sections: Dict[str, str]
    source_path: str
    content_hash: str
    word_count: int
    detected_format: DocumentFormat
    sections_found: int




class AIFocusedSECParser:
    """
    Extracts ONLY AI-relevant sections from SEC filings.

    AI-RELEVANT SECTIONS:
    - Item 1 (Business): AI strategy, technology stack
    - Item 1A (Risk Factors): Technology/cyber risks
    - Item 2 (MD&A): Recent AI developments
    - Item 7 (MD&A): R&D spending on AI
    - Item 8.01 (8-K): AI announcements
    - Executive Compensation (DEF-14A): Tech incentives
    """

    AI_RELEVANT_PATTERNS = {
        # 10-K/10-Q patterns
        "item_1_business": [
            r'(ITEM\s+1[.\s\-:]*BUSINESS[^\n]{0,100})',
            r'(Item\s+1[.\s\-:]*Business[^\n]{0,100})',
        ],
        "item_1a_risk_factors": [
            r'(ITEM\s+1A[.\s\-:]*RISK\s+FACTORS[^\n]{0,100})',
            r'(Item\s+1A[.\s\-:]*Risk\s+Factors[^\n]{0,100})',
        ],
        "item_2_mda": [
            r'(ITEM\s+2[.\s\-:]*MANAGEMENT[^\n]{0,100})',
            r'(Item\s+2[.\s\-:]*Management[^\n]{0,100})',
        ],
        "item_7_mda": [
            r'(ITEM\s+7[.\s\-:]*MANAGEMENT[^\n]{0,100})',
            r'(Item\s+7[.\s\-:]*Management[^\n]{0,100})',
        ],

        # 8-K patterns
        "item_8_01_other": [
            r'(Item\s+8\.01[^\n]{0,100})',
            r'(ITEM\s+8\.01[^\n]{0,100})',
        ],

        # DEF-14A patterns
        "executive_compensation": [
            r'(EXECUTIVE\s+COMPENSATION[^\n]{0,100})',
            r'(Executive\s+Compensation[^\n]{0,100})',
            r'(COMPENSATION\s+DISCUSSION\s+AND\s+ANALYSIS[^\n]{0,100})',
            r'(Compensation\s+Discussion\s+and\s+Analysis[^\n]{0,100})',
        ],
    }

    # Filing type detection patterns
    FILING_TYPE_PATTERNS = {
    "8-K": [r'\b8-K\b', r'CURRENT REPORT'],        # Check 8-K FIRST
    "10-K": [r'\b10-K\b', r'ANNUAL REPORT'],
    "10-Q": [r'\b10-Q\b', r'QUARTERLY REPORT'],
    "DEF-14A": [r'DEF 14A', r'PROXY STATEMENT', r'SCHEDULE 14A'],
}

    def __init__(self):
        self.stats = {
            "total": 0,
            "pdf_parsed": 0,
            "html_parsed": 0,
            "sections_found": 0,
            "ai_relevant_words": 0,
            "total_words_processed": 0
        }

    def parse_filing(
        self,
        file_path: Path,
        ticker: str = "UNKNOWN",
        filing_type_hint: Optional[str] = None
    ) -> ParsedDocument:
        """
        Parse ANY SEC filing and extract AI-relevant sections.

        Args:
            file_path: Path to SEC filing
            ticker: Company ticker (optional, defaults to "UNKNOWN")
            filing_type_hint: Optional type hint (e.g., "10-Q", "8-K")

        Returns:
            ParsedDocument with clean text and AI-relevant sections
        """
        self.stats["total"] += 1

        # Step 1: Detect format
        doc_format = self._detect_format(file_path)

        # Step 2: Extract text based on format
        if doc_format == DocumentFormat.PDF:
            raw_text = self._extract_from_pdf(file_path)
            self.stats["pdf_parsed"] += 1
        else:
            raw_text = self._extract_from_html(file_path)
            self.stats["html_parsed"] += 1

        # Step 3: Clean text
        clean_text = self._clean_text(raw_text)
        self.stats["total_words_processed"] += len(clean_text.split())

        # Step 4: Detect filing type if not provided
        if not filing_type_hint:
            filing_type_hint = self._detect_filing_type(clean_text[:10000])  # Check first 10K chars

        # Step 5: Extract AI-relevant sections
        sections = self._extract_ai_relevant_sections(clean_text)

        # Step 6: Update stats
        ai_words = sum(len(s.split()) for s in sections.values())
        self.stats["ai_relevant_words"] += ai_words
        self.stats["sections_found"] += len(sections)

        # Step 7: Build result
        return ParsedDocument(
            company_ticker=ticker,
            filing_type=filing_type_hint or "UNKNOWN",
            filing_date=datetime.fromtimestamp(file_path.stat().st_mtime, tz=timezone.utc),
            content=clean_text,
            sections=sections,
            source_path=str(file_path),
            content_hash=hashlib.sha256(clean_text.encode("utf-8")).hexdigest(),
            word_count=len(clean_text.split()),
            detected_format=doc_format,
            sections_found=len(sections)
        )

    def _detect_format(self, file_path: Path) -> DocumentFormat:
        """Detect if PDF or HTML"""
        if file_path.suffix.lower() == ".pdf":
            return DocumentFormat.PDF
        return DocumentFormat.HTML

    def _detect_filing_type(self, text: str) -> str:
        """Detect filing type from document content"""
        text_upper = text.upper()

        for filing_type, patterns in self.FILING_TYPE_PATTERNS.items():
            for pattern in patterns:
                if re.search(pattern, text_upper):
                    return filing_type

        return "UNKNOWN"

    def _extract_from_pdf(self, file_path: Path) -> str:
        """Extract text from PDF"""
        try:
            text_parts = []
            with pdfplumber.open(str(file_path)) as pdf:
                for page in pdf.pages:
                    text = page.extract_text()
                    if text:
                        text_parts.append(text)
            return "\n".join(text_parts)
        except Exception:
            return ""

    def _extract_from_html(self, file_path: Path) -> str:
        """
        Extract text from HTML - REMOVES ALL TAGS

        This is what "parsing" means!
        """
        try:
            with open(file_path, 'r', errors='ignore') as f:
                raw = f.read()

            soup = BeautifulSoup(raw, "html.parser")

            # Remove noise tags
            for tag in soup(["script", "style", "head", "meta", "link"]):
                tag.decompose()

            # Get clean text (removes ALL HTML tags)
            return soup.get_text(separator=" ")
        except Exception:
            return ""

    def _clean_text(self, text: str) -> str:
        """Clean text for pattern matching"""
        # Decode HTML entities
        text = text.replace('&#8211;', '-')
        text = text.replace('&#8212;', '-')
        text = text.replace('&nbsp;', ' ')
        text = text.replace('&amp;', '&')

        # Collapse whitespace
        text = re.sub(r'\s+', ' ', text)
        text = re.sub(r'[_]{3,}', ' ', text)

        return text.strip()

    def _extract_ai_relevant_sections(self, text: str) -> Dict[str, str]:
        """
        Extract ONLY AI-relevant sections.

        Returns:
            Dict of section_name -> section_text
        """
        found_sections = []

        # Try all AI-relevant patterns
        for key, pattern_list in self.AI_RELEVANT_PATTERNS.items():
            for pattern in pattern_list:
                match = re.search(pattern, text, re.IGNORECASE)
                if match:
                    found_sections.append((key, match.start(), match.group(1).strip()))
                    break  # Found this item, move to next

        # Sort by position in document
        found_sections.sort(key=lambda x: x[1])

        # Extract text between sections
        sections = {}
        for i, (key, start, header) in enumerate(found_sections):
            # Find end of section
            if i + 1 < len(found_sections):
                end = found_sections[i + 1][1]
            else:
                # Last section: take max 50K words (~250K chars)
                end = min(start + 250000, len(text))

            section_text = text[start:end].strip()

            # Only include substantial sections (>200 words)
            if len(section_text.split()) > 200:
                sections[key] = section_text

        return sections

    def get_efficiency_report(self) -> str:
        """Generate efficiency report"""
        if self.stats["total_words_processed"] == 0:
            return "No documents processed"

        efficiency = (self.stats["ai_relevant_words"] /
                     self.stats["total_words_processed"] * 100)

        return f"""
AI-Focused Parsing Efficiency Report:
--------------------------------------
Total documents parsed: {self.stats['total']}
  - PDF files: {self.stats['pdf_parsed']}
  - HTML files: {self.stats['html_parsed']}

Content processed:
  - Total words: {self.stats['total_words_processed']:,}
  - AI-relevant words: {self.stats['ai_relevant_words']:,}
  - Efficiency: {efficiency:.1f}%

Sections extracted:
  - Total AI-relevant sections: {self.stats['sections_found']}

Cost savings:
  - Processing time: {100 - efficiency:.1f}% faster
  - Storage: {100 - efficiency:.1f}% less
  - LLM API costs: {100 - efficiency:.1f}% cheaper
"""


