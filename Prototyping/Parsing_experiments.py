@dataclass
class Chunk:
    idx: int
    text: str
    words: int
    section: str


# ----------------------------
# Chunking strategies
# ----------------------------
def sections_only(sections: Dict[str, str]) -> List[Chunk]:
    """Keep each section whole"""
    return [
        Chunk(i, txt, len(txt.split()), name)
        for i, (name, txt) in enumerate(sections.items())
    ]


def fixed_1000(sections: Dict[str, str]) -> List[Chunk]:
    """Split all sections into 1000-word chunks (100-word overlap)"""
    chunks, idx = [], 0

    for name, txt in sections.items():
        words = txt.split()
        start = 0

        while start < len(words):
            end = min(start + 1000, len(words))
            chunk_txt = " ".join(words[start:end])
            chunks.append(Chunk(idx, chunk_txt, end - start, name))
            idx += 1

            if end == len(words):
                break
            start = end - 100

    return chunks


def hybrid_5000(sections: Dict[str, str]) -> List[Chunk]:
    """<5000 words = whole, >=5000 words = chunked"""
    chunks, idx = [], 0

    for name, txt in sections.items():
        words = txt.split()

        if len(words) < 5000:
            chunks.append(Chunk(idx, txt, len(words), name))
            idx += 1
        else:
            start = 0
            while start < len(words):
                end = min(start + 1000, len(words))
                chunk_txt = " ".join(words[start:end])
                chunks.append(Chunk(idx, chunk_txt, end - start, name))
                idx += 1

                if end == len(words):
                    break
                start = end - 100

    return chunks


