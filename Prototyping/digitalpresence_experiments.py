@dataclass
class TechnologyDetection:
    """Represents a detected technology."""
    name: str
    category: str
    is_ai_related: bool
    confidence: float
    source: str
    url: str = ""
    detected_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> dict:
        return asdict(self)

@dataclass
class DigitalPresenceAnalysis:
    """Complete digital presence analysis for a company."""
    company: str
    ticker: str
    sector: str


    # Technologies
    ai_technologies: List[TechnologyDetection]
    all_technologies: List[TechnologyDetection]

    # Scoring (per Case Study 2, Section 4.3)
    digital_presence_score: float  # 0-100
    tech_score_component: float    # 0-50
    category_score_component: float  # 0-50

    # Metadata
    categories_found: Set[str]
    confidence: float
    sources_checked: List[str]
    analyzed_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> dict:
        return {
            'company': self.company,
            'ticker': self.ticker,
            'sector': self.sector,
            'domain': self.domain,
            'digital_presence_score': self.digital_presence_score,
            'tech_score_component': self.tech_score_component,
            'category_score_component': self.category_score_component,
            'ai_technologies': [t.to_dict() for t in self.ai_technologies],
            'categories_found': list(self.categories_found),
            'confidence': self.confidence,
            'sources_checked': self.sources_checked,
            'metadata': {
                'total_technologies': len(self.all_technologies),
                'ai_tech_count': len(self.ai_technologies),
            },
            'analyzed_at': self.analyzed_at
        }

