    def deduplicate(self, technologies: List[TechnologyDetection]) -> List[TechnologyDetection]:
        """Remove duplicates, keep highest confidence."""
        seen = {}
        for tech in technologies:
            key = (tech.name.lower(), tech.category.lower())
            if key not in seen or tech.confidence > seen[key].confidence:
                seen[key] = tech
        return list(seen.values())

    def calculate_score(self, ai_technologies: List[TechnologyDetection]) -> tuple:
        """Calculate Digital Presence Score (Case Study 2 formula)."""
        categories = set(t.category for t in ai_technologies)

        tech_score = min(len(ai_technologies) * 10, 50)
        category_score = min(len(categories) * 12.5, 50)
        total_score = tech_score + category_score

        return (round(total_score, 1), round(tech_score, 1), round(category_score, 1))

    async def analyze_company(self, ticker: str) -> DigitalPresenceAnalysis:
        """Perform complete analysis using multiple URLs per source."""

        if ticker not in COMPANY_SOURCES:
            raise ValueError(f"Unknown ticker: {ticker}")

        company_info = COMPANY_SOURCES[ticker]
        company_name = company_info['name']

        print(f"\n{'='*80}")
        print(f"🔍 ANALYZING: {company_name} ({ticker})")
        print(f"   Sector: {company_info['sector']}")
        print(f"{'='*80}")

        all_technologies = []
        sources_checked = []

        async with async_playwright() as p:
            browser = await p.chromium.launch(
                headless=self.headless,
                args=['--disable-blink-features=AutomationControlled']
            )

            # 1. Tech Blogs (PRIMARY) - Loop through all
            tech_blogs = company_info.get('tech_blogs', [])
            if tech_blogs:
                print(f"  📊 PRIMARY: Tech Blogs ({len(tech_blogs)} URL{'s' if len(tech_blogs) > 1 else ''})")
                for idx, blog_url in enumerate(tech_blogs, 1):
                    try:
                        print(f"     [{idx}/{len(tech_blogs)}] Checking blog...")
                        techs = await self.scrape_tech_blog(
                            browser,
                            blog_url,
                            company_name
                        )
                        if techs:
                            all_technologies.extend(techs)
                            if "Tech Blog" not in sources_checked:
                                sources_checked.append("Tech Blog")
                    except Exception as e:
                        print(f"     ❌ Blog {idx} failed: {str(e)}")

            # 2. GitHub (SECONDARY) - Loop through all orgs
            github_orgs = company_info.get('github_orgs', [])
            if github_orgs:
                print(f"  📊 SECONDARY: GitHub ({len(github_orgs)} org{'s' if len(github_orgs) > 1 else ''})")
                for idx, github_url in enumerate(github_orgs, 1):
                    try:
                        print(f"     [{idx}/{len(github_orgs)}] Checking GitHub org...")
                        techs = await self.scrape_github(
                            browser,
                            github_url,
                            company_name
                        )
                        if techs:
                            all_technologies.extend(techs)
                            if "GitHub" not in sources_checked:
                                sources_checked.append("GitHub")
                    except Exception as e:
                        print(f"     ❌ GitHub {idx} failed: {str(e)}")

            # 3. Careers (FALLBACK) - Loop through all pages
            careers = company_info.get('careers', [])
            if careers:
                print(f"  📊 FALLBACK: Careers ({len(careers)} page{'s' if len(careers) > 1 else ''})")
                for idx, career_url in enumerate(careers, 1):
                    try:
                        print(f"     [{idx}/{len(careers)}] Checking careers page...")
                        techs = await self.scrape_careers(
                            browser,
                            career_url,
                            company_name
                        )
                        if techs:
                            all_technologies.extend(techs)
                            if "Careers" not in sources_checked:
                                sources_checked.append("Careers")
                    except Exception as e:
                        print(f"     ❌ Careers {idx} failed: {str(e)}")

            await browser.close()

        # Deduplicate (critical with multiple URLs!)
        all_technologies = self.deduplicate(all_technologies)
        ai_technologies = [t for t in all_technologies if t.is_ai_related]
        categories = set(t.category for t in ai_technologies)

        # Calculate score
        total_score, tech_score, category_score = self.calculate_score(ai_technologies)

