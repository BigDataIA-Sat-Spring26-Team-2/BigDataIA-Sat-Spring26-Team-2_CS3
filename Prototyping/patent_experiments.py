async def get_patent_count(ticker: str, company: dict) -> dict:
    """Get just the patent count for one company (fast)."""
    url = build_url(company['assignee'])

    async with async_playwright() as p:
        browser = await p.chromium.launch(
            headless=True,
            args=['--no-sandbox', '--disable-setuid-sandbox']
        )
        page = await browser.new_page()

        try:
            await page.goto(url, wait_until='networkidle', timeout=30000)
            await page.wait_for_timeout(3000)

            # Extract count
            content = await page.content()
            count = 0

            match = re.search(r'About\s+(\d+)\s+results?', content, re.IGNORECASE)
            if match:
                count = int(match.group(1))
            else:
                text = await page.evaluate('() => document.body.innerText')
                match = re.search(r'(\d+)\s+results?', text, re.IGNORECASE)
                if match:
                    count = int(match.group(1))

            return {
                'ticker': ticker,
                'company': company['name'],
                'patent_count': count,
                'url': url,
                'status': 'success'
            }

        except Exception as e:
            return {
                'ticker': ticker,
                'company': company['name'],
                'patent_count': 0,
                'url': url,
                'status': f'error: {str(e)}'
            }
        finally:
            await browser.close()

