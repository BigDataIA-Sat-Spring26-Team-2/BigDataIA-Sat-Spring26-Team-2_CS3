@dataclass
class PatentSignal:
    ticker: str
    company_name: str
    assignee_name: str
    verification_url: str
    total_patents: int
    recent_patents: int
    ai_categories: Set[str]
    patent_count_score: float = 0.0
    recency_bonus_score: float = 0.0
    category_diversity_score: float = 0.0
    normalized_score: float = 0.0
    collection_date: datetime = field(default_factory=datetime.now)
    confidence: float = 0.85  # High confidence for keyword+date method

    # Debug info
    dates_found: List[str] = field(default_factory=list)
    keyword_matches: Dict[str, int] = field(default_factory=dict)

def build_url(assignee: str) -> str:
    cpc_query = " OR ".join([f"CPC=({code})" for code in AI_CPC_CODES])
    params = {'q': cpc_query, 'assignee': assignee, 'after': 'priority:20210101', 'num': '100'}
    return f"https://patents.google.com/?{urlencode(params, safe='():/')}"

async def analyze_page_content(url: str) -> Dict:
    """
    Load page and extract:
    1. Patent count
    2. Categories from keywords
    3. Recent patents from dates
    """
    async with async_playwright() as p:
        browser = await p.chromium.launch(
            headless=True,
            args=['--no-sandbox', '--disable-setuid-sandbox']
        )
        page = await browser.new_page()

        try:
            print(f"Loading page...")
            await page.goto(url, wait_until='networkidle', timeout=130000)
            await page.wait_for_timeout(8000)

            # Get all text content
            page_text = await page.evaluate('() => document.body.innerText')
            page_html = await page.content()

            # Combine for searching
            full_text = f"{page_text} {page_html}".lower()

            # STEP 1: Extract patent count
            count = 0
            match = re.search(r'about\s+(\d+)\s+results?', full_text)
            if match:
                count = int(match.group(1))
            else:
                match = re.search(r'(\d+)\s+results?', full_text)
                if match:
                    count = int(match.group(1))

            print(f"✓ Found {count} patents")

            # STEP 2: Find categories from keywords
            categories_found = set()
            keyword_matches = {}

            for category, keywords in CATEGORY_KEYWORDS.items():
                matches = 0
                for keyword in keywords:
                    # Count occurrences
                    matches += full_text.count(keyword.lower())

                if matches > 0:
                    categories_found.add(category)
                    keyword_matches[category] = matches

            print(f"✓ Categories detected: {', '.join(sorted(categories_found)) if categories_found else 'none'}")
            for cat, matches in keyword_matches.items():
                print(f"    {cat}: {matches} keyword matches")

            # STEP 3: Find dates (YYYY-MM-DD format)
            date_pattern = r'20\d{2}-\d{2}-\d{2}'
            dates_found = re.findall(date_pattern, full_text)

            # Parse and count recent dates (after Feb 4, 2024 = 1 year ago)
            one_year_ago = datetime(2024, 2, 4)
            recent_count = 0

            for date_str in dates_found:
                try:
                    date = datetime.strptime(date_str, '%Y-%m-%d')
                    if date > one_year_ago:
                        recent_count += 1
                except:
                    continue

            # If we found dates, estimate recent patents
            # Otherwise use 50% heuristic
            if len(dates_found) > 0:
                # Average dates per patent, then count recent
                avg_dates_per_patent = len(dates_found) / max(count, 1)
                estimated_recent = int(recent_count / max(avg_dates_per_patent, 1))
            else:
                estimated_recent = int(count * 0.5)  # Fallback: 50%

            print(f"✓ Dates found: {len(dates_found)} total, {recent_count} recent")
            print(f"✓ Estimated recent patents: {estimated_recent}")

            return {
                'count': count,
                'categories': categories_found,
                'recent_patents': estimated_recent,
                'keyword_matches': keyword_matches,
                'dates_found': dates_found[:10]  # Keep sample
            }

        except Exception as e:
            print(f"❌ Error: {e}")
            return {
                'count': 0,
                'categories': set(),
                'recent_patents': 0,
                'keyword_matches': {},
                'dates_found': []
            }
        finally:
            await browser.close()

def calculate_score(ticker: str, company: dict, url: str, analysis: Dict) -> PatentSignal:
    """Calculate score from analysis results."""

    count = analysis['count']
    categories = analysis['categories']
    recent = analysis['recent_patents']

    # PDF Formula (page 18-19)
    count_score = min(count * 5, 50)
    recency_score = min(recent * 2, 20)
    diversity_score = min(len(categories) * 10, 30)
    total = count_score + recency_score + diversity_score

    print(f"\nScore Calculation:")
    print(f"  Patent Count:    {count} × 5 = {count_score}/50")
    print(f"  Recency Bonus:   {recent} × 2 = {recency_score}/20")
    print(f"  Category Diversity: {len(categories)} × 10 = {diversity_score}/30")
    print(f"  {'─'*50}")
    print(f"  TOTAL:           {total}/100")

    return PatentSignal(
        ticker=ticker,
        company_name=company['name'],
        assignee_name=company['assignee'],
        verification_url=url,
        total_patents=count,
        recent_patents=recent,
        ai_categories=categories,
        patent_count_score=count_score,
        recency_bonus_score=recency_score,
        category_diversity_score=diversity_score,
        normalized_score=total,
        dates_found=analysis['dates_found'],
        keyword_matches=analysis['keyword_matches']
    )

